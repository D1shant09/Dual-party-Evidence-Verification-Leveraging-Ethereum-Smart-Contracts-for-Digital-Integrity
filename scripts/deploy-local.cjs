const fs = require("node:fs");
const path = require("node:path");
const { ethers, artifacts } = require("hardhat");

async function main() {
  const [deployer] = await ethers.getSigners();
  console.log("Deploying DocumentVerification to local Hardhat chain");
  console.log("Chain ID: 31337");
  console.log("Deployer:", deployer.address);
  console.log("Deployer balance:", ethers.formatEther(await ethers.provider.getBalance(deployer.address)), "ETH (test ETH)");

  const Factory = await ethers.getContractFactory("DocumentVerification");
  const contract = await Factory.deploy();
  await contract.waitForDeployment();
  const address = await contract.getAddress();

  const root = path.resolve(__dirname, "..");
  const frontend = path.join(root, "safeDocFe", "src");
  const artifact = await artifacts.readArtifact("DocumentVerification");
  fs.writeFileSync(
    path.join(frontend, "ABI", "DocumentVerificationABI.json"),
    JSON.stringify(artifact.abi, null, 2) + "\n"
  );
  fs.writeFileSync(
    path.join(frontend, "constants", "constants.jsx"),
    `// Auto-generated by scripts/deploy-local.cjs. Re-run npm run deploy:local after resetting the local chain.\nexport const CONTRACT_ADDRESS = "${address}";\n`
  );

  console.log("Contract deployed at:", address);
  console.log("Updated frontend contract address and ABI.");
  console.log("Use MetaMask network: DocSafe Local Hardhat (chain ID 31337).");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
